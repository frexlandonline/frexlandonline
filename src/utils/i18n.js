let currentLanguage = localStorage.getItem('frexland_lang');

if (!currentLanguage) {
  // Auto-detect based on browser
  const browserLang = navigator.language || navigator.userLanguage;
  if (browserLang.toLowerCase().startsWith('es')) {
    currentLanguage = 'es';
  } else {
    currentLanguage = 'en';
  }
  localStorage.setItem('frexland_lang', currentLanguage);
}

export function getLang() {
  return currentLanguage;
}

export function setLang(lang) {
  if (translations[lang]) {
    currentLanguage = lang;
    localStorage.setItem('frexland_lang', lang);
    // Reload the page to apply translations everywhere easily
    window.location.reload();
  }
}

export function t(key) {
  return translations[currentLanguage][key] || translations['en'][key] || key;
}
